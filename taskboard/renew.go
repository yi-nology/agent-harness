// renew.go —— 租约续期与接管代次的契约（issue #87）。
//
// # 它补的是哪一段
//
// 长任务必然撞上租约到期：执行时长超过 Until 而没有续期手段，宿主只能在
// 「估一个很大的租约」与「永久占用」之间二选一——估大了，持有者崩了之后
// 任务要白等很久才被接管；估小了，活还没干完闸就没了。
//
// 更要害的是接管后的世界：旧持有者（GC 停顿、网络分区后恢复）迟到的提交，
// 此前只能靠「新旧令牌恰好不同」保安全——那是碰巧，不是判据。
//
// # Renew 不是心跳，是资格检查
//
// 它同时做两件事，缺一不可：
//
//  1. 把到期时刻推后（长动作不至于中途失去闸）；
//  2. 校验令牌仍是该任务的最新一代——不是则拒绝，**不做任何修改**。
//
// 只做第 1 条的续期是**假续期**：租约已被接管时，延长的其实是**别人的闸**，
// 持有者却以为延长的是自己的，于是两份闸同时开着，同一份工作被做两遍。
//
// # 接管代次（Fence）与令牌同源
//
// 代次与令牌在同一次 Claim 的同一次原子操作里铸造，同一任务上**严格递增**
// （Renew 不递增——续期不是接管）。它给两样东西：
//
//   - 判据：接管后的新代必须大于旧代（boardtest 的「接管代次严格递增」钉住，
//     代次不递增的实现必红）；
//   - 栅栏：宿主的下游资源可凭「代次比已见过的最大值小」拒收过期持有者的
//     迟到写入（与 sideeffect.FencedSink 同一形态、同一纪律）。
//
// 旧持有者迟到的提交不需要专门的判别机制：令牌不匹配即 @@ErrLeaseLost@@。
// 接管必然铸造新令牌，故迟到提交**必然**被拒，且不波及新持有者。
package taskboard

import "context"

// Fence 接管代次（栅栏令牌）：同一任务上**每次认领成功**都严格递增。
//
// 与 @@Lease.Token@@ **同源**：同一次认领的同一次原子操作里由存储铸造。
// Renew **不**递增它——续期不是接管，代次只回答「这是第几任持有者」。
//
// 首次认领的取值不限（从 0 或 1 起都可以），契约只要求同一任务上
// **严格递增**：新代必须大于旧代。
//
// 用途：
//
//   - 判据：接管后的代次必须递增（boardtest 的「接管代次严格递增」钉住，
//     代次不递增的实现必红）；
//   - 栅栏：宿主的下游资源可凭「代次比已见过的最大值小」拒收过期持有者的
//     迟到写入——与 sideeffect.FencedSink 同一形态、同一纪律
//     （比较与写入须在下游的同一次原子操作里完成）。
type Fence uint64

// RenewingBoard 支持租约续期的 Board。
//
// # 为什么是单独的接口而不是并进 Board
//
// 续期要求存储提供「校验持有资格 + 延长到期时刻」的**原子**操作——不是每份
// 既有实现都具备。并进 Board 等于让全部实现同时破；单独成接口则由判定方按
// 类型断言认人：**接入 boardtest 套件的实现必须实现它**（套件对缺失硬失败，
// 不跳过——跳过等于把「没测过」伪装成「通过」）。
//
// # Renew 的契约（存储侧必须全部保证）
//
// Renew 续期并**同时确认持有资格**，语义是「我还持有吗，顺便把有效期推后」：
//
//   - token 不是该任务当前租约的令牌 ⇒ @@ErrLeaseLost@@，**不做任何修改**。
//     不许静默成功：过期持有者的迟到续期延长的是**别人的闸**；
//   - 租约**已过期** ⇒ @@ErrLeaseLost@@。资格在到期时刻终止——过期后任务随时
//     可能被接管，存储不能既承诺「过期随时可接管」又给死者续命。想继续做，
//     重新 Claim：要么拿到新租约（新令牌新代次），要么明确得到 @@ErrTaken@@，
//     不会拿着旧身份悄悄续命；
//   - 资格校验与延长在**同一次原子操作**里完成（否则「校验通过」与「续期
//     生效」之间仍有窗口，接管者与续期者可以同时得手）；
//   - TTL 语义与 Claim **完全一致**：正数 ⇒ 按存储**自己的**当前时刻推算新的
//     到期时刻；零值 ⇒ 不限期（到期时刻清零，宿主自担）；
//   - 续期**不**递增 @@Fence@@、**不**更换 token（不是接管），返回的 Task.Seq
//     应前进（Until 变了，这是一次任务变更）。
//
// 宿主应在**施加副作用之前**调 Renew：返回 @@ErrLeaseLost@@ 说明任务已易主，
// 本次动作必须放弃——继续做就是与新持有者重复施加。
type RenewingBoard interface {
	Board
	// Renew 续期并确认持有资格（契约见类型级说明）。
	Renew(ctx context.Context, id TaskID, token string, req ClaimRequest) (Task, error)
}
