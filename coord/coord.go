// Package coord 分布式协调后端的**适配形态约定**：一个后端要接上本仓的
// 协调契约（taskboard.Board / sideeffect.Store），要按什么形状表达
// 「一次原子操作」「条件更新」「CAS 循环」。
//
// 生命周期: Experimental（v0.35.0 定级）——本包仍会改、删、拆，不承诺任何
// 兼容，升级风险自负；定级理由见 api-lifecycle.yaml，分级规则见
// docs/api-compat.md。
//
// # 它补的是哪一段（issue #107）
//
// 本仓的协调契约全部是**存储中立**的：sideeffect.Store / taskboard.Board /
// checkpoint.StoreCAS 只定语义，实现由宿主提供。真实后端的参考适配此前只有
// PostgreSQL 一种（examples/pgstore）——「后端不止一种，且形态有约定」
// 那一半是空的：宿主接 Redis / etcd 时没有任何形态可抄，各自发明
// 「读-判-写」三步实现，把跨进程原子性写丢（sideeffect 包头警告的头号窗口）。
//
// 本包把形态收成**一条代码级的约定**而不是一篇散文：
//
//  1. @@Backend@@：协调后端的最小原语集（快照读 / 条件事务 / 前缀列键）。
//     任何后端（Redis / etcd / 单机文件）只要实现这三个方法，
//  2. @@BoardAdapter@@ / @@StoreAdapter@@：把契约的三判合一、资格联查、
//     执行意图等**全部判定逻辑**落在原语之上——判定逻辑只有这一份实现，
//     宿主的后端只负责让原语真的原子。
//
// 于是「接一个新后端」的工作量从「重写一遍 Store 的 29 条契约语义」
// 缩成「实现三个原语 + 让它们在存储侧真的原子」。
//
// # 形态约定：三种原语在各后端怎么表达
//
//   - **快照读（Snapshot）**：一次取多键的一致视图。
//     Redis → 一条 Lua 脚本内 MGET（脚本内无并发写）；etcd → 一个只读 txn
//     （shared 读，同 revision）；PostgreSQL → 一条 SELECT（单语句一致性）。
//   - **条件事务（Txn）**：全部断言成立才执行全部写入，否则一个都不执行。
//     Redis → Lua 脚本（单线程执行天然原子；断言写在脚本开头，不满足即返回 0）；
//     etcd → txn（If 全部成立才 Then）；PostgreSQL → 事务内的
//     SELECT … FOR UPDATE + 条件 UPDATE。
//   - **CAS 循环**：断言失败（applied=false）→ 取新快照 → 重判 → 再事务。
//     这是适配器的通用收尾：判（快照）与写（事务）之间有窗口，冲突就重来。
//     Redis 有 Lua 时整个判定可推进脚本里、免循环；etcd/PG 保留循环即可。
//
// # 各后端的原子性边界（能保证什么、不能保证什么）
//
//   - **Redis**：单 Lua 脚本内的多键读写在脚本执行期间原子（单线程模型）；
//     脚本之间无隔离保证——跨脚本的「读后写」必须整段进同一个脚本。
//     附加约束：集群模式下多键必须同 slot（hash tag）；主从复制异步，
//     主挂时会丢已确认的写——用它当协调状态需要等价于共识的部署形态
//     （如 RedLock 的争议面），宿主自担。
//   - **etcd**：txn 的 If/Then/Else 是一次真正的原子比较交换，revision 全局
//     单调——天然适合当版本与栅栏。边界：性能量级远低于 Redis（raft 落盘），
//     不适合高频租约续期；watch 的语义边界（历史窗口）与本包无关。
//   - **PostgreSQL**：事务隔离下的条件更新（examples/pgstore 已示范）。
//     本包不重复它——那条路径的参考在 pgrefstore 模块。
//   - **内存（@@MemoryBackend@@）**：进程内互斥锁，**跨进程原子性不存在**。
//     只用于测试与演示——拿它上生产等于以为自己在去重，实际两个进程各做一次
//     （sideeffect 包头警告的原话）。它在本包的用途是给适配器当测试保底：
//     让「判定逻辑这份实现」在没有真实后端时也能被契约套件验证。
//
// # 与「判定逻辑单份实现」的边界声明
//
// 本包是**机制**：适配器的判定逻辑（判据归内核）+ 原语契约（原子性归存储）。
// 它**不是**「一份生产可用的存储」——单靠本包什么都没有，
// 必须有一个真原子的 Backend 才成立。这与 sideeffect「不给参考存储实现」
// 的纪律不冲突：那份纪律拦的是「内存实现被当成生产存储」，
// 本包的内存后端只垫在**判定逻辑**与**契约套件**之间，且在类型名上写明边界。
package coord

import "github.com/oekit/pkg/errors"

// ErrTxnConflict CAS 循环重试到上限仍未提交（高争用或后端行为异常）。
//
// 循环上限是防挂死的兜底：正常争用几次内必收敛；持续冲突说明有调用方
// 在高频改同一批键（或后端根本没实现原子性），此时把冲突显式交上去，
// 不无限重试。
var ErrTxnConflict = errors.New("coord: 条件事务反复冲突，重试上限内未提交")

// ErrMalformedRecord 键下的记录无法解码（后端里的字节与本包的编码不一致）。
//
// 它说明这批键不是本适配器写的（键前缀撞了，或后端被别的写者占用）——
// 放行会把别人的字节当自己的状态判，静默给出错误结论。
var ErrMalformedRecord = errors.New("coord: 记录解码失败（键下内容不是本适配器的编码）")
