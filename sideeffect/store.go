package sideeffect

import (
	"context"
	"time"
)

// Store 副作用闸的存储边界。宿主实现（Redis / PostgreSQL / etcd 皆可）。
//
// # Acquire 必须是一个原子操作
//
// 这是本接口**唯一的硬要求**，也是整个包成立的前提：
// 「这个 Key 做过没有」「这个资源谁占着」「发第几代令牌」三者的判定
// 必须在存储侧的**一次**原子操作里完成。
//
// 若宿主实现成「读闸 → 进程内判 → 写闸」三步，那么两个 worker 会同时
// 读到「没做过、资源空闲」，各自认定自己该做——同一动作被施加两次，
// 而本包的所有判据都显示为绿。这是本包要封的头号窗口。
//
// 典型实现形态：
//   - 一条带条件的 UPDATE（WHERE fence < :next AND done = false）；
//   - 一个 Redis Lua 脚本（多键读写在脚本内原子执行）；
//   - 一个 etcd transaction（compare-and-swap）。
//
// # 两份状态：Key 级与资源级
//
// 本接口管着**两份**状态，它们不是一回事，判据也不同：
//
//   - **Key 级**（幂等键）：这个逻辑动作「做过没有」「结果未知没有」
//     「有没有一次尚未裁决的尝试」。由 Key 唯一索引。
//   - **资源级**（闸）：这个资源「谁占着」「发第几代令牌」。由 Resource
//     唯一索引。
//
// 两条出口因此也分开：
//
//   - Store.Abandon：动 **Key 级**（本次尝试的账），顺带放资源；
//   - Store.Release：只动 **资源级**（闸），**不动** Key 级。
//
// # Key 级状态机
//
//	未开始 ──Acquire──> 执行中 ──Complete──> 已完成
//	                    │
//	                    ├──Abandon──────> 已放弃（= 未开始，可重新执行）
//	                    ├──MarkUncertain> 结果未知 ──ResolveUncertain(true)──> 已完成
//	                    │                       └─ResolveUncertain(false)─> 已放弃
//	                    └──租约过期且未被裁决 ──Acquire──> 结果未知
//
// 最后一行是 v0.33.0 补上的那条：**意图的存在本身就是一条判据**。
// 进程死在「施加成功、记账之前」时，存储侧没有「完成」也没有「未知」，
// 只有一条「执行中」——下一次同一 Key 的 Acquire 必须转入「结果未知」
// （要重做且声明了 RetrySafetySafe 的除外），**不得**重新授予执行权。
//
// # 宿主实现的三条硬要求
//
//  1. Acquire 是一次原子操作，且**必须**把「执行意图」与「授予令牌」写在
//     同一次操作里——分两次写就等于没写（第一次写完进程死掉 ⇒ 意图悬空，
//     第二次写完进程死掉 ⇒ 意图没写，重复施加的入口重新打开）；
//  2. 判定顺序必须与文档逐字一致（已完成 > 结果未知 > 执行中 > 资源被占 > 授予），
//     顺序写反的代价是重复施加；
//  3. 凡涉及「本次尝试是否仍归我」的判定（Complete / Renew / MarkUncertain /
//     Abandon / Release），必须**三项联查**：令牌仍是最新代（ErrFenceStale）、
//     持有者身份与授予时铸造的一致（ErrNotHolder）、租约的资源与动作的
//     资源一致（ErrResourceMismatch）。只查其中一两项，就有只偷到令牌的
//     组件冒充持有者（令牌会经下游流转）、或拿 A 资源的租约动 B 资源这类洞。
type Store interface {
	// Acquire 一次原子判定，返回「能否执行」与「若能执行则用哪一代令牌」。
	//
	// ttl 是本次持有的有效期，**必须由调用方显式给出**：租约多长是
	// 「本次动作预计要多久」的业务判断，内核不知道。故 TTL 走参数，
	// 不走实现里的硬编码常量。
	//
	// 语义（存储侧必须保证，按此顺序判）：
	//  1. 若该 Key 的动作**已完成** → 返回 OutcomeReplayed 与既有结果，
	//     不发放新令牌（已完成的动作不再需要令牌）。
	//  2. 否则若该 Key 上有**一次尚未裁决的尝试**（执行意图）：
	//     - 该尝试的租约**尚未过期** → 返回 OutcomeContended，不发放令牌
	//       （这次尝试还在进行中，同一个动作不得被施加第二次）；
	//     - 该尝试的租约**已过期** → 本次尝试的结果**未知**
	//       （可能已施加、账没记上），此时：
	//       · act.RetrySafety != RetrySafetySafe → 把该 Key **转入未知态**
	//         （持久化）并返回 OutcomeUncertain，**不得**授予执行权；
	//       · act.RetrySafety == RetrySafetySafe → 声明了「下游按幂等键去重，
	//         重做不会重复施加」，可清除该意图并继续走第 4 条。
	//  3. 否则若该 Key 处于**结果未知**态（MarkUncertain 标记的）→ 返回
	//     OutcomeUncertain，不发放令牌。
	//  4. 否则若该 Resource 正被他人持有且**租约未过期** → 返回
	//     OutcomeContended，不发放令牌。
	//  5. 否则 → 授予本次持有：令牌 = 该 Resource 上**已见过的最大值 + 1**
	//     （单调递增，不回退），**并把该 Key 的执行意图一并持久化**
	//     （意图 = 本次令牌 + 本次到期时刻），返回 OutcomeApplied。
	//
	// 第 2 条是 v0.33.0 新增的，也是本包最贵的一条判据：**意图的存在本身
	// 就是一条判据**。没有它，「进程死在施加成功之后、记账之前」这一形态
	// 在存储侧不留任何痕迹，下一次 Acquire 会重新授予执行权 ⇒ 重复施加。
	//
	// 已完成（1）的判定**优先于**占用（4）：动作已做完时，后来者应当拿到
	// 结果而不是被「资源正忙」挡住——否则调用方会把「早已完成」误判成
	// 「没轮上我」，而真相是「早就做完了」。
	//
	// 结果未知（3）**优先于**占用（4），但**次于**已完成（1）：未知态是
	// 这个 Key 头上的**硬阻塞**（再动它就是重复施加），而占用只是「等一等」。
	// 顺序写反的后果是：调用方拿到 contended 就以为「晚点重试就行」，
	// 而真相是「这个 Key 得先对账」——于是重试发生了，重复施加也就发生了。
	//
	// 第 5 条的令牌分配必须与「标记该 Key 已完成」「登记该 Key 的执行意图」
	// 同处一个原子操作面，否则会出现「发了令牌但没记住谁占着」或
	// 「记了意图却没发令牌」这类半截状态。
	//
	// 授予时还要**铸造持有者身份**（Lease.Holder，v0.33.0 起）：它是这次
	// 授予在存储侧生成的第二份凭据，不经任何下游接口流转——令牌会传给
	// 下游（FencedSink），持有者身份不会。铸造必须是**不可预测**的
	// （随机 / 存储侧序列派生均可），且不同授予之间不重合；
	// 调用方自选的身份等于没有身份。返回的 Lease 必须带上它。
	//
	// 返回的 Result 是**既有结果原样**（不做任何标记）：本次是否在重放
	// 由 Acquire 的 Outcome 表达，不靠结果里的一个标志位——
	// 同一件事只有一个真相。
	//
	// 动作身份不可变（v0.33.0 后新增，见 ErrActionConflict）：同一 Key
	// 首次 Acquire 登记的动作身份（Resource / Payload / RetrySafety）是
	// 这个 Key 的永久事实。后续 Acquire 的 act 与已登记身份不一致 →
	// 返回 ErrActionConflict，**不授予、不重放既有结果、不转未知态**，
	// 且判定优先于「已完成 → 重放」（把旧身份的结果交给新身份的调用方
	// 就是答非所问）。依据：RetrySafety 是「过期后能不能重试」的判据，
	// 若可被后续调用覆盖，最初不可安全重试的动作会被重新声明为安全
	// ⇒ 重复施加；Resource / Payload 同理——同 Key 不同内容不是重试。
	Acquire(ctx context.Context, act Action, ttl time.Duration) (Outcome, Lease, Result, error)

	// Complete 标记该 Key 的动作已完成并记录结果。
	//
	// 幂等：同一 Key 重复 Complete 不报错，返回首次记录的结果
	// （先到者的结果为准，不被后到者覆盖）。
	//
	// 必须带凭据：存储侧**三项联查**（见包级硬要求第 3 条）——令牌仍是
	// 当前 Resource 的最新代、持有者身份与授予时铸造的一致、租约与动作的
	// 资源一致——只在三项全过时才接受这次完成。过期持有者的迟到
	// Complete 会被拒（否则它会用旧结果覆盖新持有者刚写入的结果——
	// 更新的状态被旧状态覆盖，与栅栏要防的正是同一件事）；只偷到令牌的
	// 组件的冒充 Complete 也会被拒（ErrNotHolder）。
	//
	// 完成之后该 Key 的执行意图一并撤销（这次尝试已有结论）。
	Complete(ctx context.Context, act Action, lease Lease, res Result) (Result, error)

	// Release 释放**资源持有**（闸），**不动**该 Key 的执行意图。
	//
	// # 为什么它不是「一切了事」
	//
	// Acquire 把「本次执行的意图」原子地持久化在 Key 上（见 Acquire 第 5 条）。
	// 意图没被裁决之前，这个 Key 不得再被执行——否则「施加成功但进程死在
	// 记账之前」这一形态会被下一次 Acquire 变成重复施加。
	//
	// 故两条出口必须分开，**不可互相替代**：
	//   - 干净收场（确定没生效，或下游按幂等键去重、重做安全）
	//     → **Abandon**（清意图 + 放资源）；
	//   - 结果未知（可能已生效）→ **MarkUncertain**（转未知态）+ Release
	//     （只放资源）。
	//
	// ⚠️ 在「结果未知」这条路上误用 Abandon ⇒ 意图被清 ⇒ 该 Key 重新
	// 变成「可被执行」⇒ 重复施加的入口重新打开。两条出口分开正是为了
	// 让这个误用不再是「顺手就能写出来」的代码。
	//
	// 存储侧须保证：只释放**自己**的持有（三项联查通过才放；Release 同样
	// 要校验持有者身份与资源一致），否则一个过期持有者迟到的 Release 会把
	// 新持有者的闸放掉（与 commitgate「凭令牌释放、不认内容」同一条纪律）。
	//
	// 释放**不**把该 Key 标记为已完成——动作没做完就是没做完。
	Release(ctx context.Context, act Action, lease Lease) error

	// Abandon **显式放弃**本次尝试：撤销该 Key 的执行意图，并释放资源持有。
	//
	// 语义：调用方确认「这次尝试没有产生副作用」或「下游按幂等键去重，
	// 重做不会重复施加」⇒ 该 Key 之后**可重新被执行**。
	//
	// 与 Release 的分工见 Release 的注释：一句话——**Abandon 动 Key 级，
	// Release 只动资源级**。
	//
	// 存储侧须保证：
	//  1. 只撤销**本次尝试**的意图（校验该 Key 的执行意图仍归该令牌所有）；
	//     否则一个过期持有者会撤销新持有者的意图，把新持有者正在做的事
	//     变成「可重做」；
	//  2. 资源持有**只在令牌仍是最新代时**才释放（闸已易主就别碰它——
	//     那是新持有者的闸）；
	//  3. 撤销意图后，该 Key 既不是「已完成」也不是「结果未知」——
	//     下一次 Acquire 可返回 OutcomeApplied。
	Abandon(ctx context.Context, act Action, lease Lease, reason string) error

	// Renew 续期并**同时确认持有资格**。
	//
	// 它做两件事，缺一不可：
	//  1. 把本次持有的到期时刻推后 ttl（长动作不至于中途失去闸）；
	//  2. 校验本次令牌**仍是该 Resource 的最新代**——若已被他人接管，
	//     返回 ErrFenceStale，**不续期**。
	//
	// 第 2 条才是 Renew 的重点。只做第 1 条的「续期」是**假续期**：
	// 闸已经易主时，延长时间延的是别人的闸，持有者却以为延长的是自己的。
	// 于是持有者带着一份早已过期的租约继续施加副作用——
	// 而此时新持有者可能正在做同一件事。这就是「两份闸同时开着」。
	//
	// v0.33.0 起 Renew 还要校验**本次尝试仍归本持有者所有**（三项联查）：
	// 租约过期后，同一 Key 的 Acquire 可能已把这次尝试转入未知态，
	// 此时持有者回来续期 ⇒ 它要续的是一段「结果未知」的尝试，
	// 而那段尝试的结果本来就该由对账裁决，不是由持有者续期续回来。
	//
	// 因此 Renew 的语义是**「我还持有吗，顺便把有效期推后」**，
	// 不是纯心跳。宿主应在**施加副作用之前**调用它：
	// 那时若返回 ErrFenceStale，说明闸已易主或本次尝试已失效，
	// 本次动作**必须放弃**——继续做就是与新持有者重复施加。
	//
	// 过期即资格终止（无论是否已被接管）：租约**已过期而尚未被他人
	// 接管**时，旧持有者的续期同样必须被拒（ErrFenceStale）——过期是
	// 资格的终点，不是「还没人来接，所以还算数」。放行过期续期等于允许
	// GC 停顿超 TTL 的持有者复活一段已作废的租约，而它上一次施加的
	// 结果可能正是「已生效但账没记上」：复活的租约让那次尝试继续推进，
	// 绕开了 Acquire 第 2 条「过期 → 结果未知，必须先对账」的判定。
	// 这条与 taskboard.Renew 的「到期后资格终止」是同一条口径——
	// 两个包对「过期租约」的回答必须一致。
	//
	// 存储侧须保证：续期与资格校验在**同一次原子操作**里完成
	// （否则「校验通过」与「续期生效」之间仍有窗口）。
	Renew(ctx context.Context, act Action, lease Lease, ttl time.Duration) (Lease, error)

	// MarkUncertain 把该 Key 标记为「结果未知」。
	//
	// 存储侧必须保证：
	//  1. 该 Key 的下一次 Acquire 返回 OutcomeUncertain，**不得**返回
	//     OutcomeApplied——否则会盲目重试一个可能已经生效的动作。
	//  2. 标记是**按 Key** 的，与资源租约无关：闸可以释放（让别的动作用这个
	//     资源），但这个 Key 在被裁决之前**不得再被执行**。
	//  3. 幂等：重复标记同一 Key 不报错。
	//  4. 三项联查不通过时**拒绝标记**（令牌非最新代 → ErrFenceStale；
	//     持有者不匹配 → ErrNotHolder；资源不一致 → ErrResourceMismatch）。
	//     否则一个过期持有者会把新持有者刚做完的动作标成未知，而新持有者
	//     那边的结果是确定的——事实被写反了。
	//  5. **标记写失败时（本方法返回 error），该 Key 的执行意图必须原样
	//     留在存储里**（v0.33.0 起，硬要求）。标记与「撤销意图」不得在同一
	//     个操作里先撤后标——写失败的标记必须把存储留在「意图还在挡着」的
	//     状态：此时后续同一 Key 的 Acquire 必须被拒（意图未过期 ⇒ contended；
	//     意图过期 ⇒ uncertain），**不得**返回 OutcomeApplied。否则「标记
	//     失败」会退化成「没有标记」，另一个 worker 再来一次 Acquire 就
	//     重新授予执行权 ⇒ 重放一个可能已生效的动作，而第一次调用的返回值
	//     只是栈上的错误，跨进程什么都没留下。
	//
	// 标记成功后该 Key 的执行意图一并撤销（这次尝试已有结论：未知）。
	// 但**闸不会自动释放**：调用方还要显式调 Release 只放资源。
	MarkUncertain(ctx context.Context, act Action, lease Lease, reason string) error

	// ResolveUncertain 裁决「结果未知」的 Key。
	//
	// 存储侧必须保证：
	//  1. res.Applied == true → 把该 Key 记为已完成并留存 res.Result；
	//     本方法返回 OutcomeReplayed + 该结果（此刻就是「取回既有结果」），
	//     之后同一 Key 的 Acquire 同样返回 OutcomeReplayed + 该结果
	//     （重放而不是重做）。对 RetrySafetyUnsafe 的动作同样成立——
	//     「确认已生效」不涉及重试，没有风险。
	//  2. res.Applied == false → 清除未知标记，该 Key 重新可被执行
	//     （之后同一 Key 的 Acquire 可返回 OutcomeApplied），本方法返回
	//     OutcomeApplied 表达这个结论——裁决成功且门已打开，不是
	//     OutcomeContended（那会把「可执行了」误报成「没轮上」）。
	//     **例外——RetrySafetyUnsafe 的动作**（v0.33.0 起）：未生效的裁决
	//     **不解除阻塞**，返回 ErrUnsafeNotRetryable，该 Key 保持未知态。
	//     「不可重试」是宿主的显式声明，对账的「未生效」结论来自宿主的
	//     一次查询，查询本身可能出错——对这类动作，「查完说没做」不足以
	//     重新打开施加的门，必须 res.ForceRetryable == true 的**显式决策**
	//     才行。RetrySafetyUnknown（未声明）维持原语义：对账未生效即可重试。
	//  3. **先到者为准**（幂等）：同一 Key 的二次裁决不覆盖首次裁决。
	//  4. 该 Key 不在未知态时：若已完成 → 返回 OutcomeReplayed + 既有结果；
	//     否则 → 返回 ErrNotUncertain。
	//  5. 裁决**不校验栅栏**：它的依据是**下游事实**，不是持有权——
	//     原持有者可能已经死亡、租约早已过期，而对账恰恰要在这种情况下进行。
	//     （栅栏管的是「谁能写」，对账管的是「到底做没做」，两件事。）
	//  6. 裁决同时清除该 Key 的执行意图与对账占用（若有）：这次尝试已有结论。
	ResolveUncertain(ctx context.Context, act Action, res Resolution) (Outcome, Result, error)

	// BeginReconcile 认领对账权：把该 Key 标记为「对账中」并记录谁在对账、
	// 对账到什么时候（v0.33.0 新增）。
	//
	// # 为什么需要它——对账本身是个竞争窗口
	//
	// 没有对账占用时，两个对账者可以同时对同一个 Key 查下游、并同时提交
	// 裁决。ResolveUncertain 的「先到者为准」只是把冲突结果掩盖掉，不是
	// 判据：落败的那次裁决，它的下游查询成本与副作用都没人认领。也没有
	// 「对账失败」的落点——对账中途进程死亡，Key 停在未知态，与「从未
	// 开始对账」不可区分，运维看不出这条 Key 是没人管，还是管的人死了。
	//
	// 语义（存储侧必须保证）：
	//  1. 仅当该 Key 处于未知态时接受认领（否则 ErrNotUncertain）；
	//  2. 已有**未过期**的认领时拒绝（ErrReconcileTaken）——同一时刻至多
	//     一个对账者；
	//  3. 认领过期后可被重新认领（可重入）——对账者死亡不永久占住；
	//     过期的占用被下一次 BeginReconcile / Acquire 清掉；
	//  4. 认领期间该 Key 仍处于未知态：Acquire 必须继续拒绝授予执行权
	//     （对账中 ≠ 已裁决，更不等于可以重做）；
	//  5. ResolveUncertain 在未知态与对账中都可用（它是唯一裁决入口，
	//     先到者为准兜底）；裁决成功即清除占用；
	//  6. ttl <= 0 → ErrInvalidTTL，**不认领**（v0.33.0 后新增）。零/负
	//     TTL 造出的是出生即过期的认领——承诺从未生效（见该哨兵注释）。
	//
	// 调用约定：宿主先 BeginReconcile 占住对账权，再查下游，最后
	// ResolveUncertain。跳过认领直接裁决仍是合法的（短对账无须占用），
	// 但长对账（要跨进程查询）必须认领——否则就是那个竞争窗口；
	// 跨进程对账的提交要用下面 OwnedResolveStore 的带凭据入口。
	BeginReconcile(ctx context.Context, act Action, ttl time.Duration) (Reconcile, error)
}

// OwnedResolveStore 可选能力：**带对账占用凭据**的裁决入口（v0.33.0 后新增）。
//
// # 为什么 ResolveUncertain 不够——先到者为准不校验资格
//
// Store.ResolveUncertain 是合法的简化入口（短对账、单进程内查完就裁决），
// 它只按「先到者为准」处理并发。但跨进程长对账是另一个形状：
//
//	对账者 A 认领 → A 查下游（慢）→ A 卡顿超时 → 占用过期 →
//	对账者 B 接管、也开始查 → A 恢复、先于 B 提交旧查询结果
//
// 先到者为准接受 A 的裁决——**不问 A 还有没有对账资格**。而 A 的查询
// 窗口横跨了状态变化（B 可能已查到新事实），它的结论恰是最不可信的。
// 「先到者为准」解决的是「不覆盖」，不是「提交者有资格」。
//
// # 契约（存储侧必须保证）
//
//  1. holder 必须是该 Key **当前有效**对账占用的持有者：占用存在、
//     未过期、Holder 匹配——否则 ErrReconcileLost，**不改任何状态**；
//  2. 通过后的裁决语义与 Store.ResolveUncertain 完全一致（先到者为准、
//     Unsafe 判据、裁决即清占用与意图）；
//  3. 该 Key 已完成 → 返回 OutcomeReplayed + 既有结果（读操作无害，
//     不因凭据过期而拒绝读取既有事实）。
//
// 简化入口 Store.ResolveUncertain **保留**：单进程短对账里占用本就
// 可省，不强迫所有调用方持有凭据。但跨进程对账的宿主应当用本接口——
// 不实现本接口的存储编译不破，但 sidetest 套件对缺失**硬失败**
// （与 RenewingBoard 同一处置：跳过 = 把「没测过」伪装成「通过了」）。
type OwnedResolveStore interface {
	Store

	// ResolveUncertainOwned 带占用凭据的裁决：holder 不是当前有效
	// 对账认领的持有者 → ErrReconcileLost（不改任何状态）。
	ResolveUncertainOwned(ctx context.Context, act Action, res Resolution, holder string) (Outcome, Result, error)
}
